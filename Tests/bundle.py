#!/usr/bin/env python3
"""Bundle src/Zindex/*.luau plus the suite into one file the Luau CLI can run.

Modules require each other as require(script.Parent.Name), which is how Roblox
resolves siblings. Outside Roblox there is no `script`, so the bundler rewrites
those calls into lookups in a module table and runs each module in its own
function.
"""

import io
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = ['Opcodes', 'Memory', 'Devices', 'Core', 'Assembler', 'Image', 'init']


def read(path):
    return io.open(path, encoding='utf-8').read()


parts = ['-- generated by Tests/bundle.py, do not edit', 'local __mods = {}']

for name in MODULES:
    source = read(os.path.join(ROOT, 'src', 'Zindex', name + '.luau'))
    source = re.sub(r'require\(script\.Parent\.([A-Za-z_][A-Za-z0-9_]*)\)', r'__mods.\1', source)
    parts.append('\n__mods.%s = (function()\n%s\nend)()' % (name, source))

parts.append('\n__mods.Zindex = __mods.init')
parts.append('\n-- test suite\n')
parts.append(read(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'Tests', 'suite.luau')))

combined = '\n'.join(parts)
out = os.path.join(ROOT, 'Tests', 'combined.luau' if len(sys.argv) < 2 else 'debug.luau')
io.open(out, 'w', encoding='utf-8').write(combined)
print('wrote %s (%d bytes)' % (out, len(combined)))
